/**
 * TS -> Rust parity vectors for the Hyperliquid signing port.  `npm run hl:vectors`
 *
 * Runs the verified TypeScript module (src/lib/hyperliquid/exchangeSigning.ts, which reproduces
 * the official SDK vectors) over a fixed, seeded set of orders and writes every intermediate
 * value to contracts/risk-guard-v3/tests/fixtures/hl_vectors.json. The Rust tests must reproduce
 * each value byte-for-byte; tests/hlParity.test.ts fails if this file goes stale.
 * Offline only: no network.
 */
import { encode } from "@msgpack/msgpack";
import { bytesToHex } from "@noble/hashes/utils.js";
import { writeFileSync } from "node:fs";
import {
  actionHash,
  floatToWire,
  HYPERLIQUID_PERPS,
  HYPERLIQUID_PERPS_TESTNET,
  l1SigningDigest,
  orderAction,
  orderWire,
  type Tif,
} from "../src/lib/hyperliquid/exchangeSigning";
import { checkPerpPrice, lotsToE8, sizeLots, toE8 } from "../src/lib/hyperliquid/fixedPoint";
import { buildV3Hedge } from "../src/lib/hyperliquid/v3Hedge";

export const HL_VECTORS_PATH = "contracts/risk-guard-v3/tests/fixtures/hl_vectors.json";

/** Exact integer value in units of 1e-8 that floatToWire formats (its toFixed(8) step). */
const e8 = (x: number) => BigInt(x.toFixed(8).replace(".", "")).toString();

function prng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const PRICES = [100, 1670.1, 0.0147, 74363, 74423.5, 3.7498, 92.704, 1975.6, 0.00000001, 0.1, 0.5, 12345678.9, 3.6, 7442.3, 0.012345, 99999, 1, 2.5, 0.0001, 65536];
const SIZES = [0.0147, 100, 0.0002, 1, 0.1, 9242.5, 12.5, 0.00001, 3, 1000000, 0.5, 42];
const ASSETS = [0, 1, 3, 4, 5, 54, 74, 127, 128, 200, 255, 256, 10000, 65535, 65536];
const TIFS: Tif[] = ["Alo", "Ioc", "Gtc"];
const NONCES: (number | bigint)[] = [0, 1, 127, 1677777606040, 1794405483425, Number.MAX_SAFE_INTEGER, 18446744073709551615n];

export function buildHlVectors() {
  const rnd = prng(20261111);
  const pick = <T>(xs: T[]) => xs[Math.floor(rnd() * xs.length)];

  const wire = [...PRICES, ...SIZES, 0, 123.456789, 0.00000005, 9007199.25].map((x) => ({ x, e8: e8(x), wire: floatToWire(x) }));

  const orders = [];
  for (let i = 0; i < 64; i++) {
    const n = i % 16 === 15 ? 17 : i % 8 === 7 ? 3 : 1; // a few multi-order actions, one beyond fixarray size
    const list = Array.from({ length: n }, () => ({
      asset: pick(ASSETS),
      isBuy: rnd() < 0.5,
      limitPx: pick(PRICES),
      sz: pick(SIZES),
      reduceOnly: rnd() < 0.25,
      tif: pick(TIFS),
    }));
    const nonce = NONCES[i % NONCES.length];
    const isMainnet = i % 2 === 0;
    const action = orderAction(list.map((o) => orderWire(o)));
    const conn = actionHash(action, nonce);
    orders.push({
      id: i,
      nonce: nonce.toString(),
      isMainnet,
      orders: list.map((o, k) => ({
        asset: o.asset,
        isBuy: o.isBuy,
        pxE8: e8(o.limitPx),
        szE8: e8(o.sz),
        reduceOnly: o.reduceOnly,
        tif: o.tif,
        p: action.orders[k].p,
        s: action.orders[k].s,
      })),
      json: JSON.stringify(action),
      msgpackHex: bytesToHex(encode(action)),
      connectionIdHex: bytesToHex(conn),
      digestHex: bytesToHex(l1SigningDigest(conn, isMainnet)),
    });
  }

  // Exact integer sizing (fixedPoint.sizeLots, used by buildHedgeAction and the v3 mirror).
  const sizing = [];
  const CENTS = [3327335, 665551, 1000000, 1, 99, 100, 99999999, 450000000, 12345678901];
  for (const cents of CENTS) {
    for (const px of [3.6, 3.7498, 74363, 74423.5, 1975.6, 92.704, 0.0147, 1, 7442.3, 100]) {
      for (const szDecimals of [0, 1, 2, 4, 5]) {
        const lots = sizeLots(cents, toE8(px), szDecimals);
        sizing.push({ cents, pxE8: e8(px), szDecimals, lots: lots.toString(), sizeE8: lotsToE8(lots, szDecimals).toString() });
      }
    }
  }

  // Price rules (integer prices always valid; else <= 5 sig figs and <= 6 - szDecimals decimals).
  const PRICE_STRINGS = ["74363", "74423.5", "7442.3", "7442.35", "1670.1", "1670.12", "1.123", "92.704", "0.0001", "0.00001", "3.7498", "3.74985", "0.000123", "0.012345", "123456", "0", "0.1", "99999.9", "10000.5", "1.0001"];
  const priceRules = PRICE_STRINGS.flatMap((s) => [0, 1, 2, 4, 5, 6].map((szDecimals) => ({ px: s, pxE8: toE8(s).toString(), szDecimals, violation: checkPerpPrice(toE8(s), szDecimals) })));

  return {
    note: "Generated by scripts/hl-vectors.ts from src/lib/hyperliquid/{exchangeSigning,fixedPoint,v3Hedge}.ts. Do not edit by hand.",
    msgpackLibrary: "@msgpack/msgpack 3.x default options",
    wire,
    orders,
    sizing,
    priceRules,
    v3Parity: V3_PARITY,
    hedges: buildHedgeVectors(rnd),
  };
}

/** Contract-level parity: what Risk Guard v3 must build for each request (see ts_parity.rs). */
export const V3_PARITY = {
  contractId: "zerodelta-guard-v3.testnet",
  blockTimeMs: 1794405483425,
  bands: { price_band_bps: 100, notional_band_bps: 50 },
  markets: {
    testnet: Object.entries(HYPERLIQUID_PERPS_TESTNET).map(([symbol, m]) => ({ symbol, asset: m.asset, sz_decimals: m.szDecimals })),
    mainnet: Object.entries(HYPERLIQUID_PERPS).map(([symbol, m]) => ({ symbol, asset: m.asset, sz_decimals: m.szDecimals })),
  },
};

function buildHedgeVectors(rnd: () => number) {
  const REFS: Record<string, string[]> = { BTC: ["74363", "74423.5", "7442.3"], ETH: ["1975.6", "1966.6"], SOL: ["92.704", "92.3"], NEAR: ["3.7498", "3.7311"] };
  const fixed: { symbol: string; short: number; limit: string; ref: string; why: string }[] = [
    { symbol: "BTC", short: 665551, limit: "74000", ref: "74363", why: "approved" },
    { symbol: "ETH", short: 3000000, limit: "1966.6", ref: "1975.6", why: "approved" },
    { symbol: "SOL", short: 1500000, limit: "92.3", ref: "92.704", why: "approved" },
    { symbol: "NEAR", short: 3327335, limit: "3.7311", ref: "3.7498", why: "approved (v2 approved notional)" },
    { symbol: "BTC", short: 665551, limit: "72000", ref: "74363", why: "out of band" },
    { symbol: "BTC", short: 665551, limit: "74362", ref: "74363", why: "approved, 1 bps" },
    { symbol: "BTC", short: 665551, limit: "73619.37", ref: "74363", why: "price rules" },
    { symbol: "BTC", short: 665551, limit: "74423.5", ref: "74363", why: "too many sig figs" },
    { symbol: "NEAR", short: 3327335, limit: "3.74985", ref: "3.7498", why: "too many sig figs" },
    { symbol: "ETH", short: 3000000, limit: "1975.123", ref: "1975.6", why: "too many decimals" },
    { symbol: "BTC", short: 100, limit: "74000", ref: "74363", why: "notional drift (1 lot = 74 cents)" },
    { symbol: "BTC", short: 1, limit: "74000", ref: "74363", why: "size zero" },
    { symbol: "BTC", short: 665551, limit: "74000", ref: "0", why: "no reference" },
    { symbol: "BTC", short: 665551, limit: "0", ref: "74363", why: "zero limit" },
    { symbol: "NEAR", short: 99999999999, limit: "3.7311", ref: "3.7498", why: "large notional" },
  ];
  const random = Array.from({ length: 40 }, () => {
    const symbol = ["BTC", "ETH", "SOL", "NEAR"][Math.floor(rnd() * 4)];
    const ref = REFS[symbol][Math.floor(rnd() * REFS[symbol].length)];
    const bps = Math.floor(rnd() * 160) - 80; // -80..+79 bps
    const limit = Number((Number(ref) * (1 + bps / 10_000)).toPrecision(5)).toString();
    const short = [100000, 665551, 3327335, 25000000, 123456789][Math.floor(rnd() * 5)];
    return { symbol, short, limit, ref, why: `random ${bps} bps` };
  });
  return [...fixed, ...random].flatMap((c, i) =>
    (["testnet", "mainnet"] as const).map((hlNetwork) => {
      const market = V3_PARITY.markets[hlNetwork].find((m) => m.symbol === c.symbol)!;
      const order = {
        asset_symbol: c.symbol,
        treasury_usd_cents: Math.ceil(c.short / 0.6),
        spot_long_usd_cents: c.short,
        perp_short_usd_cents: c.short,
        perp_long_usd_cents: 0,
        collateral_usd_cents: Math.ceil(c.short / 0.6),
        quoted_slippage_bps: 2,
        nonce: V3_PARITY.blockTimeMs - 1000 - i,
      };
      const b = buildV3Hedge(V3_PARITY.contractId, hlNetwork, market, order, toE8(c.limit), toE8(c.ref), V3_PARITY.bands);
      return {
        why: c.why,
        hlNetwork,
        order,
        limitPxE8: toE8(c.limit).toString(),
        referencePxE8: toE8(c.ref).toString(),
        sizeE8: b.sizeE8.toString(),
        priceDeviationBps: b.priceDeviationBps.toString(),
        notionalDriftBps: b.notionalDriftBps.toString(),
        actionJson: b.actionJson,
        msgpackHex: b.msgpackHex,
        connectionIdHex: b.connectionIdHex,
        digestHex: b.digestHex,
        commitmentHex: b.commitmentHex,
        violations: b.violations,
      };
    }),
  );
}

if (process.argv[1]?.endsWith("hl-vectors.ts")) {
  const v = buildHlVectors();
  writeFileSync(HL_VECTORS_PATH, `${JSON.stringify(v, null, 1)}\n`);
  const approved = v.hedges.filter((h) => h.violations.length === 0).length;
  console.log(
    `wrote ${HL_VECTORS_PATH}: ${v.wire.length} wire, ${v.orders.length} order actions, ${v.sizing.length} sizing, ${v.priceRules.length} price-rule, ${v.hedges.length} v3 hedge cases (${approved} buildable without violations)`,
  );
}
